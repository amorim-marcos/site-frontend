function getCssBasedOnScreenSize(screenSize: ScreenSize, cssValue: string) {
  switch (screenSize) {
    case 'xs':
      return css`
        @media (max-width: ${w_xs_max}px) {
          ${cssValue}
        }
      `
    case 'sm':
      return css`
        @media (max-width: ${w_sm_max}px) {
          ${cssValue}
        }
      `
    case 'md':
      return css`
        @media (max-width: ${w_md_max}px) {
          ${cssValue}
        }
      `
    case 'lg':
      return css`
        @media (max-width: ${w_lg_max}px) {
          ${cssValue}
        }
      `
    case 'xl':
      return css`
        @media (min-width: ${w_xl_min}px) {
          ${cssValue}
        }
      `
    default:
      return css`
        ${cssValue}
      `
  }
}

function getFlexBoxHorizontal(
  direction: Direction,
  horizontal: HorizontalAlignment
) {
  if (direction === 'row') {
    switch (horizontal) {
      case 'f-l':
        return 'justify-content: flex-start;'
      case 'f-c':
        return 'justify-content: center;'
      case 'f-r':
        return 'justify-content: flex-end;'
    }
  } else {
    switch (horizontal) {
      case 'f-l':
        return 'align-items: flex-start;'
      case 'f-c':
        return 'align-items: center;'
      case 'f-r':
        return 'align-items: flex-end;'
    }
  }
}

function getFlexBoxVertical(direction: Direction, vertical: VerticalAlignment) {
  if (direction === 'row') {
    switch (vertical) {
      case 'v-t':
        return 'align-items: flex-start;'
      case 'v-m':
        return 'align-items: center;'
      case 'v-b':
        return 'align-items: flex-end;'
    }
  } else {
    switch (vertical) {
      case 'v-t':
        return 'justify-content: flex-start;'
      case 'v-m':
        return 'justify-content: center;'
      case 'v-b':
        return 'justify-content: flex-end;'
    }
  }
}

export function getAlignment(
  screenSize: ScreenSize,
  direction: Direction,
  vertical: VerticalAlignment,
  horizontal: HorizontalAlignment
) {
  return getCssBasedOnScreenSize(
    screenSize,
    `
    display: flex;
    flex-direction: ${direction};
    ${getFlexBoxHorizontal(direction, horizontal)}
    ${getFlexBoxVertical(direction, vertical)}
    `
  )
}

